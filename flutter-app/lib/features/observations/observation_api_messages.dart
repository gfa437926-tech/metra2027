/// User-facing Arabic messages for station-scoped observation API errors.
/// Does not invent server outcomes; maps known status codes only.
String observationSubmitErrorMessage(int statusCode) {
  return switch (statusCode) {
    400 => 'بيانات النشرة غير صالحة؛ راجع الحقول المطلوبة والقيم ضمن المديات.',
    401 => 'انتهت الجلسة أو يلزم تسجيل الدخول.',
    403 => 'ليست لديك صلاحية الإرسال أو هذه المحطة غير مخوّلة لحسابك.',
    409 => 'تعارض مفتاح منع التكرار أو حالة النشرة لا تسمح بالعملية.',
    422 => 'رفض الخادم التحقق من الحقول؛ صحّح القيم ثم أعد المحاولة.',
    503 => 'خدمة الرصد غير متاحة حالياً.',
    _ => 'تعذر إرسال النشرة ($statusCode).',
  };
}

